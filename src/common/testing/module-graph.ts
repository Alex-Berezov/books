/**
 * Обход метаданных `imports` вширь — транзитивное замыкание графа модулей.
 *
 * 🔴 **`undefined` в результате — не мусор, а сигнал, и его нельзя отфильтровывать.**
 * Циклический `require` оставляет в массиве `imports` дыру: при цикле
 * модуль-константа ещё не инициализирована в момент выполнения декоратора
 * `@Module`, и вместо ссылки туда попадает `undefined`. Поэтому `undefined`
 * добавляется в множество наравне с настоящими ссылками — спека проверяет его
 * отсутствие так же, как отсутствие самого модуля. Отфильтровать его «для
 * чистоты» значило бы ослепить проверку ровно на тот случай, ради которого она
 * написана (ADR-003).
 *
 * ⚠️ Проверять надо **транзитивное** замыкание, а не прямые `imports`. Прямая
 * проверка `imports.not.toContain(X)` ловит цикл длиной 2 и слепа к циклу через
 * посредника: `A → B → C → A` она пропускает.
 *
 * ⚠️ **Предел обхода: динамические модули и `forwardRef` — листья.** В массиве
 * `imports` может стоять не ссылка на класс, а объект `DynamicModule`
 * (`X.forRoot()`) или обёртка `forwardRef(() => X)`. Метаданных `imports` у них
 * нет, поэтому обход на таком ребре молча заканчивается и цикл за ним не виден.
 * Сегодня это безопасно: ни один из семи графов, которые проверяются этим
 * хелпером, динамических модулей в `imports` не содержит (проверено 11.08.2026).
 * Появится первый — обход надо будет учить разворачивать `.module` у
 * `DynamicModule` и вызывать функцию у `forwardRef`.
 *
 * Вынесено из шести побайтно одинаковых копий в спеках модулей прав
 * (`LEGACY-042`): выносить было некуда, пока в скоупе не появился не-спековый
 * файл. Седьмая копия появилась бы при четырнадцатом модуле.
 */
export function collectTransitiveImports(root: unknown): Set<unknown> {
  const visited = new Set<unknown>();
  const queue: unknown[] = [root];
  while (queue.length > 0) {
    const current = queue.shift();
    const imports = (Reflect.getMetadata('imports', current as object) as unknown[]) ?? [];
    for (const imported of imports) {
      if (visited.has(imported)) continue;
      visited.add(imported);
      if (imported !== undefined) queue.push(imported);
    }
  }
  return visited;
}
