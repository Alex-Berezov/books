import { collectRoutes, type ControllerRoute } from './controller-decorators';

/**
 * `LEGACY-010`. Публичный маршрут, у которого есть языковой двойник, — это один
 * и тот же контент по двум адресам: `/pages/:slug` рядом с `/:lang/pages/:slug`.
 * Язык у безъязыкого выбирался по `?lang` и `Accept-Language`, то есть один адрес
 * отдавал разное тело разным запросам — недетерминированный язык индексируемой
 * страницы плюс дубль в выдаче.
 *
 * Три таких маршрута сняты 14.09.2026 решением владельца (тема №3 «Публичные
 * адреса»): `GET /pages/:slug`, `GET /categories/:slug/books`, `GET /tags/:slug/books`.
 *
 * 🔴 Сторож устроен храповиком, а не списком запрещённого. Список запрещённого
 * ловит ровно то, что в нём перечислено, и молчит о четвёртом таком маршруте;
 * храповик краснеет от нового двойника сам. Уменьшать `KNOWN_LANGLESS_TWINS`
 * можно и нужно — это и есть работа; пополнять его нельзя: новый двойник означает,
 * что публичный адрес заведён в обход темы владельца.
 *
 * ⚠️ Граница у храповика одна, и она названа здесь, а не подразумевается: язык ищется
 * **первым сегментом пути** (`/:lang/...`), потому что публичный контур устроен так.
 * Пара с языком в середине — `/admin/pages` и `/admin/:lang/pages`
 * (`pages.controller.ts`) — сторожем не видится и в его предмет не входит: адрес
 * админский, в поисковую выдачу не попадает, а расширение проверки покраснело бы
 * на этой живой паре в тот же день.
 *
 * Маршруты без языкового двойника сторож не трогает вовсе: `/books/:id`,
 * `/categories/tree`, `/health` и прочие языку не подчиняются, и требовать
 * от них префикса было бы неправдой о предметной области.
 */

/**
 * Безъязыкие двойники, которые ещё живы. Список только сокращается — это храповик,
 * и дописывание строки сюда ради зелёного прогона запрещено прямо в шапке файла.
 *
 * Было пять: класс оказался шире записи `LEGACY-010`, и выяснил это сам сторож
 * на первом прогоне. 15.09.2026 владелец разрешил снять все пять, но разведка
 * показала, что предпосылка разрешения («потребителей на фронте нет ни у одного»)
 * верна только для двух. Сняты они: `/books/:param/overview` и `/seo/resolve`.
 *
 * Остался один, и он вне предмета записи (`LEGACY-387`, решение арбитра 15.09.2026):
 *
 * - `/categories` и `/tags` сняты 23.09.2026 (`W6`, половина 2): карта сайта
 *   переведена на `getPublicCategories`/`getPublicTags`, админские пикеры — на
 *   гвардованные `GET /admin/categories` и `GET /admin/tags`, а три публичные
 *   страницы таксономии, звавшие `/categories` напрямую, — на языковой адрес.
 *   Разрешение владельца получено 21.09.2026 дословно: «разрешаю снять
 *   безъязыкие адреса после перевода потребителей на `/:lang/...`».
 * - `/books` в предмет записи не входит вовсе: он закрыт
 *   `@UseGuards(JwtAuthGuard, RolesGuard)` с ролями `Admin`/`ContentManager`
 *   (`book.controller.ts`, правка `LEGACY-093`), то есть публичным адресом
 *   не является и в поисковую выдачу не попадает. Публичного языкового двойника
 *   с черновиками не существует. Он лежит здесь только как совпадение по пути:
 *   сторож разбирает путь и гвардов не учитывает — расширять его признаком гварда
 *   запрещено тем же решением арбитра.
 */
const KNOWN_LANGLESS_TWINS: ReadonlyArray<string> = ['/books'];

/**
 * `all` учитывается наравне с `get`: `@All('pages/:slug')` отвечает на `GET /pages/about`
 * ровно так же, как `@Get`, и сторож, видящий только один из двух декораторов, зелен
 * от слепоты (`controller-decorators.ts:182-188` — тот же довод).
 */
const READ_VERBS: ReadonlyArray<ControllerRoute['verb']> = ['get', 'all'];

/**
 * 🔴 Имя параметра стирается перед сравнением. Двойник ищется по совпадению пути,
 * и `/pages/:pageSlug` рядом с живым `/:lang/pages/:slug` — тот же самый дубль:
 * `GET /pages/about` отвечает и там и там. Сравнение с именами оставляло дыру
 * ровно на переименование параметра — то есть на одну букву в обход сторожа.
 */
const normalize = (path: string): string => path.replace(/:[^/]+/g, ':param');

const pathsOf = (routes: ControllerRoute[]): Set<string> =>
  new Set(
    routes.filter((route) => READ_VERBS.includes(route.verb)).map((route) => normalize(route.path)),
  );

describe('LEGACY-010: публичный маршрут не дублирует языковой без префикса', () => {
  // Гвард не назван — `collectRoutes()` кладёт весь разбор в `open`.
  const { open, skipped } = collectRoutes();
  const paths = pathsOf(open);

  /** `/pages/:slug` при живом `/:lang/pages/:slug` — двойник; `/health` — нет. */
  const langlessTwins = [...paths]
    .filter((path) => !path.startsWith('/:param/'))
    .filter((path) => paths.has(`/:param${path}`))
    .sort();

  it('снятых маршрутов в коде нет', () => {
    // Сравнение идёт по нормализованному пути, поэтому возврат под другим именем
    // параметра (`/pages/:pageSlug`) краснит этот кейс так же, как возврат один в один.
    //
    // Трое сняты 14.09.2026 (`LEGACY-010`), двое — 15.09.2026, ещё двое —
    // 23.09.2026 (все четыре — `LEGACY-387`).
    expect(paths.has('/pages/:param')).toBe(false);
    expect(paths.has('/categories/:param/books')).toBe(false);
    expect(paths.has('/tags/:param/books')).toBe(false);
    expect(paths.has('/books/:param/overview')).toBe(false);
    expect(paths.has('/seo/resolve')).toBe(false);
    expect(paths.has('/categories')).toBe(false);
    expect(paths.has('/tags')).toBe(false);
  });

  it('новых безъязыких двойников не появилось', () => {
    expect(langlessTwins).toEqual([...KNOWN_LANGLESS_TWINS].sort());
  });

  /**
   * 🔴 Без этого кейса сторож зелен от слепоты, а не от чистоты. Контроллер, у которого
   * `decoratorBlocks` не нашёл блока декораторов класса, уходит в `skipped` и пропадает
   * из `paths` целиком — вместе с любым безъязыким маршрутом внутри. Оба кейса выше
   * тогда проходят вхолостую, а порог `paths.size` потерю одного файла из двух с лишним
   * сотен маршрутов не замечает.
   */
  it('ни один контроллер не выпал из разбора', () => {
    expect(skipped).toEqual([]);
  });

  it('разбор вообще что-то видит — иначе сторож зелен от пустоты', () => {
    expect(paths.size).toBeGreaterThan(100);
  });
});
