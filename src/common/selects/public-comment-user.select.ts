import { Prisma } from '@prisma/client';

/**
 * Поля автора комментария, которые можно показать читателю (`LEGACY-089`,
 * `LEGACY-191`).
 *
 * 🔴 Причина существования константы — почта третьих лиц. Список жил локальным
 * литералом в `comments.service.ts`, а `users.service.ts` писал свой такой же
 * от руки — и с почтой, в обоих вложенных селектах `getActivities`. Когда
 * `LEGACY-089` убирала почту из публичной выдачи комментариев, эти два литерала
 * той правкой не задело вовсе: они одинаковые по составу, но разные по тексту,
 * и связи между ними в коде не было. `GET /users/me/activities` продолжал
 * отдавать любому вошедшему адреса тех, кому он отвечал, и тех, кто ответил
 * ему, — а это третьи лица.
 *
 * 🔴 `id` в списке остаётся осознанно: он нужен разметке, но по нему однажды
 * открывалась вторая утечка — `reader-bootstrap?userId=` отдавал чужой прогресс
 * чтения (`LEGACY-088`). Идентификатор автора считается публичным ровно до тех
 * пор, пока ни один маршрут не пускает по нему в чужие данные.
 *
 * ⚠️ Константа общая на два модуля намеренно, и это продолжение того же довода,
 * по которому её завели в `comments.service.ts`: там селект повторялся в шести
 * местах, и забыть одно из шести было ровно так же легко, как не заметить почту
 * во всех шести сразу. Пока список жил внутри модуля комментариев, счёт мест
 * всё равно рос — сегодня их семь: пять в комментариях и два в `getActivities`.
 *
 * ⚠️ Список **белый**, а не `omit`. Новая колонка схемы не появится в ответе,
 * пока её не впишут сюда руками, — тот же довод, что в комментарии
 * к `PUBLIC_BOOK_VERSION_SELECT`.
 *
 * 🔴 Почта сюда не добавляется никогда. Место, где пользователь смотрит на
 * себя, и админский список закрыты `ACCOUNT_USER_SELECT`; отдельный админский
 * запрос (`CommentsService.adminList` под `RolesGuard`) собирает свой select и
 * этой константой не пользуется намеренно — там почта нужна для поиска по ней.
 */
export const PUBLIC_COMMENT_USER_SELECT = {
  id: true,
  name: true,
  nickname: true,
  avatarUrl: true,
} satisfies Prisma.UserSelect;
