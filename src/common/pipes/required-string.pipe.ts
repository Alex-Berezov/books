import { ArgumentMetadata, BadRequestException, Injectable, PipeTransform } from '@nestjs/common';

/**
 * Обязательный строковый параметр запроса (`LEGACY-193`).
 *
 * 🔴 Тип `string` в сигнатуре обработчика описывает намерение, а не то, что
 * реально пришло: `@Query('key') key: string` получает `undefined`, если
 * параметра нет, и первое же обращение к нему падает `TypeError`. Клиент
 * получает 500 вместо 400, а `SentryExceptionFilter` шлёт в Sentry именно 5xx —
 * то есть забытый параметр превращается в алерт о падении сервера.
 *
 * ⚠️ Глобальный `ValidationPipe` здесь не помогает и заменить этот пайп не
 * может: у скалярного параметра нет класса, а значит нет и метаданных
 * `class-validator`, по которым `@IsNotEmpty()` вообще применяется. Форма
 * «навесить `new ValidationPipe()` на параметр» нерабочая — проверять там
 * нечего.
 *
 * ⚠️ Пайп отбивает **отсутствие и пустоту**, и ничего сверх того. Формат
 * значения — дело вызывающего: сузить его здесь значит менять контракт
 * маршрута, а не чинить 500.
 *
 * ⚠️ Значение возвращается **как пришло**, без `trim`, хотя пустота
 * определяется по `trim()`. Это не рассогласование, а граница: обрезка меняла
 * бы само значение, а ключ объекта в хранилище — идентичность строки, и
 * ` covers/a.jpg` с пробелом это другой ключ, а не тот же самый с опечаткой.
 * Пробельная строка отбивается потому, что она заведомо не ключ ничего;
 * решать за вызывающего, что делать с пробелом внутри непустого значения,
 * пайп не вправе.
 *
 * ⚠️ Бросает `BadRequestException`, а не `NotFoundException`. Соседний
 * `LangParamPipe` маскирует отказ под 404 намеренно — он стоит на публичных
 * маршрутах и прячет структуру адресов; здесь маршруты закрыты входом, и
 * прятать нечего, а 404 вместо 400 вернул бы ту же неразличимость, из-за
 * которой запись и заведена.
 */
@Injectable()
export class RequiredStringPipe implements PipeTransform<unknown, string> {
  transform(value: unknown, metadata: ArgumentMetadata): string {
    // Имя параметра берётся из метаданных, а не задаётся при навешивании:
    // иначе оно разъедется с `@Query('...')` при первом же переименовании.
    const name = metadata.data ?? 'parameter';
    if (typeof value !== 'string' || value.trim() === '') {
      throw new BadRequestException(`${name} is required`);
    }
    return value;
  }
}
