/**
 * Чужой текст в промпте - данными между границами `<<<LABEL` и `LABEL>>>`, а не инструкцией
 * (`F05-5`): исходник и перевод в промптах проверок, замечания проверяющего в промпте перевода.
 * Текст книги в промптах перевода и досье пока идёт без ограды. Разделители внутри текста
 * вырезаются - иначе текст закрыл бы ограду и продолжил промпт своими словами.
 */
export function fenced(label: string, text: string): string {
  // До неподвижной точки: вырезанный разделитель склеивает соседние знаки в новый («>><<<>»).
  let data = text;
  let next = data.replace(/<<<|>>>/g, '');
  while (next !== data) {
    data = next;
    next = data.replace(/<<<|>>>/g, '');
  }
  return `<<<${label}\n${data}\n${label}>>>`;
}
