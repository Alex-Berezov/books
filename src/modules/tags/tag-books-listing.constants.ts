import { BOOK_CARDS_MAX_LIMIT } from '../book/dto/book-cards-query.dto';

/** Дефолт маршрута до появления DTO задавался сигнатурой сервиса, здесь он тот же. */
export const PUBLIC_TAG_BOOKS_DEFAULT_LIMIT = 20;

/**
 * Потолок не свой, а тот же, что у соседнего `/{lang}/tags/{slug}/books/cards`: маршруты
 * отдают один и тот же список книг тега, и разные потолки на них означали бы, что объём
 * выдачи зависит от того, какой из двух адресов выбрал потребитель. Именно константа,
 * а не литерал `48`: одинаковое число, записанное дважды, расходится при первой же правке
 * одного из мест, и видно это станет только на живом запросе. Строка здесь тяжелее -
 * `PUBLIC_BOOK_VERSION_SELECT` вместо карточки, - так что более высокий потолок
 * не нужен тем более.
 *
 * Потолок жёсткий: `@Max` в `PublicTagBooksQueryDto` плюс `Math.min` в
 * `TagsService.versionsByTagLangSlug` вторым рубежом. Отказ, а не молчаливое обрезание:
 * обрезанный список выглядит полным, и потребитель, делящий `total` на запрошенный
 * `limit`, насчитает страницы, которых нет.
 */
export const PUBLIC_TAG_BOOKS_MAX_LIMIT = BOOK_CARDS_MAX_LIMIT;
