/** Размер страницы публичного списка авторов по умолчанию — столько просит хаб. */
export const PUBLIC_AUTHORS_DEFAULT_LIMIT = 24;

/**
 * Потолок публичного списка авторов. Жёсткий: `@Max` в DTO плюс `Math.min` в сервисе.
 *
 * 🔴 Мягкий зажим — вернуть сотню вместо запрошенной тысячи без ошибки — здесь
 * **опаснее** честного 400, и это не общее соображение, а разбор конкретного вызова.
 * `books-front/app/sitemaps/[filename]/route.ts:379` собирает этим списком множество
 * «кто видим на других языках» для hreflang авторских страниц, а решение об
 * альтернативе принимается так (`route.ts:424-427`):
 *
 * ```
 * linkable: language === lang
 *        || !linkableByLang.has(language)
 *        || (linkableByLang.get(language)?.has(author.id) ?? false)
 * ```
 *
 * - Запрос **упал** → языка нет в карте → `!has(language)` истинно → альтернатива
 *   остаётся. Отказ трактуется как «язык неизвестен», и это сознательный выбор
 *   проекта: лишняя альтернатива дешевле потерянной.
 * - Запрос **вернул усечённые 100 из 300** → язык в карте есть, автора в нём нет →
 *   `linkable: false` → живая альтернатива тихо выкидывается.
 *
 * То есть 400 на устаревшем вызове — громкий отказ с безопасным поведением, а
 * молчаливое усечение — ровно та тихая потеря, против которой в том файле стоит
 * отдельный комментарий. Поэтому потолок объявлен и валидатором тоже (`B19`),
 * а не только зажимом внутри сервиса.
 *
 * ⚠️ Порядок выката от этого не отменяется: фронт не позже бэка. Уедет бэк первым —
 * карта сайта на время рассинхрона оставит все языковые альтернативы и напишет
 * в логи `Error fetching authors for hreflang`.
 *
 * 100, а не 48: сотней уже ходит соседний обход карты сайта (`route.ts:352`), и потолок
 * ниже фактического размера страницы был бы новым тихим обрезанием. Хаб просит 24
 * и о потолке не знает вовсе.
 */
export const PUBLIC_AUTHORS_MAX_LIMIT = 100;

/** Порядок публичного списка: по имени либо по числу книг. */
export type PublicAuthorsSort = 'name' | 'books';

export const PUBLIC_AUTHORS_SORTS: PublicAuthorsSort[] = ['name', 'books'];
