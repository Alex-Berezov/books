import { createHash } from 'node:crypto';

/**
 * Редактор значений, уезжающих во внешний сервис вместе с событием Sentry
 * (`LEGACY-115`, `LEGACY-188`, `LEGACY-331`, `LEGACY-332`).
 *
 * Вынесен из `sentry.filter.ts` 30.08.2026: ни одна из этих функций не читает
 * состояние фильтра, а проверять их через мок `ArgumentsHost` и области событий
 * дороже, чем прямым вызовом.
 */

/**
 * Ключи, значения которых не уезжают во внешний сервис (`LEGACY-115`).
 *
 * 🔴 Маска существует с самого начала, но применялась только к телу запроса,
 * а `headers`, `query` и `params` уходили в событие как есть. В заголовках
 * лежат `Authorization` с рабочим JWT и `Cookie` с сессией, то есть в проекте
 * Sentry оседали действующие токены доступа тех, чей запрос упал с 5xx.
 *
 * ⚠️ Регистр не важен: Express отдаёт имена заголовков в нижнем регистре
 * (`authorization`, `cookie`), а тело запроса приходит в чужом регистре
 * (`Authorization`, `accessToken`), и оба случая закрывает флаг `i`.
 *
 * ⚠️ Совпадение частичное и это намеренно: `accessToken`, `refresh_token`,
 * `set-cookie` и `proxy-authorization` попадают под маску сами.
 *
 * ⚠️ Шесть слов добавлены 30.08.2026 решением арбитра (`LEGACY-332`). Слова
 * `key` и `otp` в список **не** взяты намеренно: `key` совпадает с `monkey`
 * и `keyword`, а заодно с законным query-параметром `key` в `POST /uploads/confirm`
 * и `DELETE /uploads` (`uploads.controller.ts`) — там это имя объекта в хранилище,
 * единственное, по чему разбирается сбой заливки, а не секрет; `otp`
 * совпадает с `notPublished` и `notPurchased`. Маскировать несуществующее
 * сегодня поле ценой потери живой диагностики — плохой обмен.
 */
const SENSITIVE_KEY_PATTERN =
  /password|token|authorization|secret|cookie|credential|signature|jwt|session|apikey|api[-_]key/i;

/**
 * Имя ключа, приведённое к словам через нижнее подчёркивание (`LEGACY-334`).
 *
 * 🔴 Персональные маски сверяются со **словами** ключа, а не с его подстрокой.
 * `/email/i.test('voicemail')` истинно: ключ `voicemailNumber` отдал бы телефон,
 * заменённый бессмысленным почтовым хешем. Поля с таким именем в проекте нет —
 * дефект был латентным, а не состоявшимся, — но разбор «слишком широко или в самый
 * раз», сделанный для `SENSITIVE_KEY_PATTERN`, для персональной маски не делался
 * вовсе. Правило `L-008` — про это же.
 *
 * ⚠️ `SENSITIVE_KEY_PATTERN` на разбор по словам **не** переводится и работает
 * по сырому имени: `set-cookie`, `refresh_token` и `api[-_]key` держатся
 * подстрокой намеренно, и над-совпадение секретной маски ошибается в безопасную
 * сторону. Решение арбитра от 30.08.2026.
 *
 * ⚠️ Череда заглавных разрезается отдельным правилом: `APIEmail` даёт
 * `api_email`, а не `apiemail`, иначе слово `email` в нём не нашлось бы.
 */
export function normalizeKey(key: string): string {
  return key
    .replace(/([a-z0-9])([A-Z])/g, '$1_$2')
    .replace(/([A-Z]+)([A-Z][a-z])/g, '$1_$2')
    .replace(/[^a-zA-Z0-9]+/g, '_')
    .toLowerCase();
}

/**
 * Ключи, значения которых уезжают в событие **хешем, а не открытым текстом**
 * (`LEGACY-332`). Сверяется с `normalizeKey`, а не с сырым именем.
 *
 * 🔴 Это не секреты, а персональные данные, и разница определяет обращение.
 * Секрет надо стереть: он не нужен для разбора вовсе. Почта нужна — но не сама,
 * а лишь как ответ на вопрос «упало у одного человека двести раз или у двухсот
 * человек по разу». Хеш этот вопрос закрывает, а личность не выдаёт.
 *
 * ⚠️ Проверяется **после** `SENSITIVE_KEY_PATTERN`, а не до: `emailConfirmToken`
 * попадает под оба, и это секрет, а не почта, — он должен стираться целиком.
 *
 * ⚠️ И **до** `PERSONAL_FILTERED_KEY_PATTERN`: `claimantEmail` попадает под обе
 * персональные маски, и порядок решает, останется ли он хешем. Стёртая почта
 * заявителя убила бы счёт уникальных пострадавших, ради которого хеш и выбран
 * (`LEGACY-332`). Решение арбитра от 30.08.2026.
 *
 * ⚠️ Почему второй канал вообще существовал: `LEGACY-187` закрыл только `setUser`,
 * а тело `POST /auth/login`, упавшего в 500, клало в событие открытую почту рядом
 * с маршрутом и `ip`. На входе пользователь ещё не вошёл, `setUser` пуст, и почта
 * в теле — единственное, что отличает один упавший вход от другого.
 */
const PERSONAL_HASHED_KEY_PATTERN = /(^|_)email(_|$)/;

/**
 * Ключи, значения которых **стираются**: персональные данные, различимость
 * которых разбору не нужна (`LEGACY-334`). Сверяется с `normalizeKey`.
 *
 * 🔴 Хеш здесь был бы хуже маски, а не лучше. Пространство значений телефона
 * и имени мало, несолёный хеш от них обратим перебором — то есть псевдоанонимизация,
 * а не анонимизация. Различимость события заявитель и так даёт хешем почты, и второй
 * различающий признак не нужен вовсе. Решение арбитра от 30.08.2026.
 *
 * ⚠️ Слово `claimant` закрывает все шесть персональных полей заявителя DMCA сразу
 * (`claimantName`, `claimantOrganization`, `claimantPhone`, `claimantAddress`,
 * `claimantEmail`, `counterNoticeClaimantName`).
 *
 * 🔴 Но маской по имени ключа правовая ручка **не закрывается целиком**, и это
 * стоило одного отменённого решения. В тех же телах лежит обязательная проза
 * без `@MaxLength` — `counterNoticeTextRu` (`record-counter-notice.dto.ts:7`),
 * `descriptionRu` и `originalNoticeText` (`create-rights-claim.dto.ts:165,186`),
 * `responseTextRu` (`record-claim-response.dto.ts:8`). Встречное уведомление DMCA
 * по своей форме и есть контактный блок отправителя: имя, адрес и телефон в нём
 * лежат текстом, под именем ключа, которое персональным не назовёшь. По ключу
 * они не ловятся никогда, по значению не разбираются — поэтому для маршрутов
 * `admin/rights` включается `RedactAllowList`, и он единственный их закрывает.
 * Найдено ревью 30.08.2026; решение арбитра того же дня отменило предыдущее.
 *
 * ⚠️ Заодно стираются `claimantType`, `claimantIsAuthorized` и `claimantPersonId` —
 * тип заявителя, флаг полномочий и идентификатор персоны. Это принятая цена,
 * исключений для них не заводится: список исключений разъедет маску при первом же
 * новом поле. По той же причине их нет и в белом списке — до него они не доходят.
 *
 * ⚠️ Слова `address`, `author`, `birth`, `text` и `description` сюда **не** берутся.
 * `address` вне `claimant` встречается только литералами JSON-LD в `seo.service.ts`
 * и в тело запроса не попадает; `text` и `description` совпали бы с двумя десятками
 * живых ключей (`metaDescription`, `ogDescription`, `attributionTextsRu`,
 * `requiredAttributionText`) — это тот самый обмен диагностики на несуществующую
 * утечку, который запись велела не делать. Слово `name` не взято по той же причине,
 * но точный ключ `name` взят — см. `PERSONAL_EXACT_KEYS`.
 */
const PERSONAL_FILTERED_KEY_PATTERN =
  /(^|_)(claimant|phone|organization|full_?name|first_?name|last_?name|nick_?name)(_|$)/;

/**
 * Персональные ключи, совпадающие **целиком**, а не словом (`LEGACY-334`).
 *
 * 🔴 `name` попало сюда точным ключом, а не словом, и разница здесь решает всё.
 * Словом оно совпало бы с `file_name`, `agent_name`, `event_name`, `role_name`
 * и ещё двумя десятками живых ключей — событие о сбое заливки перестало бы
 * называть файл. Целиком гаснет только голое `name`, а в телах, где оно живое
 * (рубрика, метка, импорт), рядом всегда лежат `key` и `slug`: личность записи
 * в событии сохраняется, теряется только подпись.
 *
 * ⚠️ Закрывает достижимую утечку, а не гипотетическую: `RegisterDto.name`
 * (`auth.dto.ts:15`) и `UpdateMeDto.name` (`users.controller.ts:97`) — это имя
 * живого человека в теле запроса, и упавший в 500 вход клал его в событие рядом
 * с уже хешированной почтой и `ip`. Ровно сценарий `LEGACY-332`, только именем.
 * Найдено ревью 30.08.2026; решение арбитра того же дня.
 */
const PERSONAL_EXACT_KEYS: ReadonlySet<string> = new Set(['name']);

/**
 * Белый список имён ключей: всё, чего в нём нет, стирается (`LEGACY-334`).
 *
 * 🔴 Чистый параметр редактора. Какие маршруты его получают, решает
 * `sentry.filter.ts` — здесь про маршруты не знают вовсе, и это намеренно:
 * редактор вынесен из фильтра 30.08.2026 именно как не читающий состояние.
 *
 * ⚠️ Имена сверяются с `normalizeKey`, как и персональные маски.
 */
export type RedactAllowList = ReadonlySet<string>;

/**
 * Сколько шестнадцатеричных знаков хеша уходит в событие (`LEGACY-332`).
 *
 * ⚠️ Двенадцати хватает, чтобы совпадение двух разных почт в пределах одного
 * разбора инцидента было невероятным, и мало, чтобы значение выглядело
 * пригодным к чему-то, кроме сравнения на равенство.
 */
const HASH_PREFIX_LENGTH = 12;

/**
 * Хеш **несолёный** и оттого стабильный между перезапусками и инстансами:
 * счёт уникальных пострадавших иначе не сходится. Соль из окружения — тема
 * владельца, а соль на процесс после рестарта в цикле падений даёт уверенно
 * неверный счёт. Решение арбитра от 30.08.2026.
 *
 * ⚠️ Нормализация обязательна: `User@Example.COM ` и `user@example.com` — один
 * человек, и без `trim().toLowerCase()` они дали бы два разных хеша, то есть
 * ровно ту ошибку счёта, ради которой хеш и выбран вместо маски.
 */
function hashPersonalValue(value: string): string {
  const normalized = value.trim().toLowerCase();
  const digest = createHash('sha256').update(normalized, 'utf8').digest('hex');
  return `[Hashed: ${digest.slice(0, HASH_PREFIX_LENGTH)}]`;
}

/**
 * Обращение с ключом по его имени: секрет стирается, персональное уходит хешем,
 * остальное отдаётся на обычный обход.
 *
 * 🔴 Помощник один на оба цикла — по ключам объекта и по параметрам строки
 * запроса — намеренно. Написанный дважды, этот разбор разъезжается при первой же
 * правке: новое правило обращения с почтой легло бы в цикл по объекту и не дошло
 * до строки запроса, и тогда `body` и `url` одного события дали бы по одной
 * и той же почте два разных значения, то есть двух «людей» вместо одного.
 * Найдено ревью 30.08.2026 до коммита.
 *
 * ⚠️ Порядок трёх проверок обязателен и задан решением арбитра от 30.08.2026:
 * секрет → почта → прочее персональное. `emailConfirmToken` попадает под первую
 * и вторую, и это секрет, а не почта; `claimantEmail` — под вторую и третью,
 * и это почта, которая должна остаться хешем, а не стереться.
 *
 * ⚠️ Персональные маски сверяются с `normalizeKey`, секретная — с сырым именем.
 * Расхождение намеренное и объяснено у самих констант.
 *
 * ⚠️ Нестроковое значение под персональным ключом (объект, массив, число) — это
 * не почта, а неизвестно что: нормализовать его нечем, а `String(value)` дал бы
 * стабильный хеш от `[object Object]`, то есть ложное «это все один человек».
 * Такое значение стирается.
 */
function redactByKey(
  key: string,
  value: unknown,
  allow?: RedactAllowList,
): { handled: true; value: string } | undefined {
  if (SENSITIVE_KEY_PATTERN.test(key)) return { handled: true, value: '[Filtered]' };
  const normalized = normalizeKey(key);
  if (PERSONAL_HASHED_KEY_PATTERN.test(normalized)) {
    return { handled: true, value: redactPersonalValue(value) };
  }
  if (PERSONAL_FILTERED_KEY_PATTERN.test(normalized) || PERSONAL_EXACT_KEYS.has(normalized)) {
    return { handled: true, value: '[Filtered]' };
  }
  // Белый список проверяется **последним**: снять маску с уже совпавшего ключа
  // он не вправе. Иначе достаточно было бы внести имя в список, чтобы вернуть
  // наружу почту или секрет.
  if (allow && !allow.has(normalized)) return { handled: true, value: '[Filtered]' };
  return undefined;
}

/**
 * ⚠️ Пустое и пробельное значение хешу не отдаётся. Хеш пустой строки —
 * константа, одинаковая у всех: клиент, отправляющий пустое поле, дал бы
 * в событиях один и тот же `[Hashed: e3b0c44298fc]`, и разбор увидел бы
 * одного настойчивого пользователя вместо множества разных. Ровно та же
 * причина, по которой стирается нестроковое значение.
 * Найдено ревью 30.08.2026 до коммита.
 */
function redactPersonalValue(value: unknown): string {
  if (typeof value !== 'string' || value.trim() === '') return '[Filtered]';
  return hashPersonalValue(value);
}

/**
 * Потолок длины одной строки в событии (`LEGACY-336`).
 *
 * 🔴 До 01.09.2026 потолка не было вовсе: обязательная проза правовой заявки
 * без `@MaxLength` (`counterNoticeTextRu`, `descriptionRu`, `originalNoticeText`,
 * `responseTextRu`) уезжала в событие целиком, если ключ не гасился.
 *
 * ⚠️ 512, а не 250 SDK: `maxValueLength` клиента режет только `event.message`,
 * `exception.value` и `request.url` (`@sentry/core/utils/prepareEvent.js:144-154`),
 * до значений внутри `contexts` он не доходит. Здесь потолок вдвое мягче,
 * потому что режется уже разобранное поле, а не всё сообщение сразу.
 */
export const MAX_FREE_TEXT_LENGTH = 512;

/**
 * Адрес почты внутри произвольного текста (`LEGACY-336`).
 *
 * ⚠️ Форма нарочно широкая: ошибка в сторону лишнего хеша стоит одного
 * нечитаемого токена в диагностике, ошибка в другую сторону стоит утечки.
 * Так же выбрана и `SENSITIVE_KEY_PATTERN`. Версия вида `pkg@1.2.beta`
 * под неё попадёт — это принятая цена (решение арбитра от 01.09.2026).
 *
 * 🔴 **Квантификаторы ограничены, и это про цену прохода, а не про строгость.**
 * Первая форма писалась как `[A-Za-z0-9.-]+\.`, где точка входит в класс перед
 * литеральной точкой: на входе без завершающего домена движок перебирает хвост
 * заново с каждой стартовой позиции, то есть даёт квадратичный откат. Тело
 * `POST /api/comments` потолка длины не имеет (`create-comment.dto.ts:43-46`),
 * а `express.json` пускает мегабайт — строка из полумиллиона знаков с одной
 * собакой посередине укладывала единственный поток Node на любом 5xx.
 * Здесь домен разобран на метки: точка **только** литеральная, внутри метки
 * её нет, неоднозначного разбиения не возникает вовсе. Найдено ревью 01.09.2026.
 */
const EMAIL_VALUE_PATTERN = /[A-Za-z0-9._%+-]{1,64}@(?:[A-Za-z0-9-]{1,63}\.){1,8}[A-Za-z]{2,24}/g;

/**
 * Разбор строки **по значению**, а не по имени ключа (`LEGACY-336`, `LEGACY-337`).
 *
 * До 01.09.2026 обращение со значением выбиралось только по имени ключа
 * (`redactByKey`), и там, где имя ни с чем не совпало или имени нет вовсе —
 * элемент массива, значение под безопасным ключом, поисковый `q`, — строка
 * уезжала как есть. Решение арбитра от 01.09.2026.
 *
 * ⚠️ Заменяется **только совпадение**, а не вся строка: «что искали, когда
 * упало» — главный признак разбора, и стирание его убило бы. Поэтому `q`
 * и не внесён ни в одну маску по имени: тот же параметр несёт номер заявки,
 * слаг и произвольный текст.
 *
 * ⚠️ Хеш берётся тот же, что и по ключу (`hashPersonalValue`): иначе одна
 * и та же почта из `claimantEmail` и из прозы дала бы в событии двух разных
 * «людей», то есть ровно ту ошибку счёта, ради которой хеш выбран вместо маски.
 *
 * 🔴 Порядок обязателен: сначала хеш, потом потолок. Наоборот адрес,
 * попавший на границу усечения, разрезался бы пополам и первая половина
 * уехала бы открытой.
 */
export function redactFreeText(value: string): string {
  // Ранний выход: собаки нет — разбирать нечего, и регулярка не запускается
  // вовсе. Это подавляющее большинство строк любого события.
  const hashed = value.includes('@')
    ? value.replace(EMAIL_VALUE_PATTERN, (match) => hashPersonalValue(match))
    : value;
  if (hashed.length <= MAX_FREE_TEXT_LENGTH) return hashed;
  const dropped = hashed.length - MAX_FREE_TEXT_LENGTH;
  return `${hashed.slice(0, MAX_FREE_TEXT_LENGTH)}[Truncated: ${dropped} more chars]`;
}

/**
 * Предел глубины обхода в `redactKeys` (`LEGACY-188`). Вход — уровень 1.
 *
 * ⚠️ Четыре, а не пять: все наблюдаемые формы мельче (`{ user: { password } }`
 * и `?filter[token]=` — второй уровень), а меньшая глубина ошибается
 * в безопасную сторону. Непройденный контейнер заменяется меткой и утечь
 * не может; теряется только диагностика. Решение арбитра от 30.08.2026.
 */
const MAX_REDACT_DEPTH = 4;

/**
 * Сколько элементов массива уходит в событие целиком (`LEGACY-188`).
 *
 * ⚠️ Событие Sentry имеет предел размера и обрезается молча, теряя как раз
 * хвост. Явный потолок с меткой об усечении отличает «их было больше»
 * от «столько и было».
 */
const MAX_REDACT_ARRAY_ITEMS = 20;

/**
 * Общий редактор ключей для всего, что кладётся в контекст события.
 *
 * ⚠️ Любое новое поле контекста обязано проходить через него — это записано
 * правилом в `LEGACY-115`, потому что заголовки миновали маску ровно так:
 * поле добавили рядом с уже замаскированным телом и сочли вопрос закрытым.
 *
 * ⚠️ Проход **рекурсивный** с 30.08.2026 (`LEGACY-188`): вложенное
 * `{ user: { password } }` и `{ items: [{ token }] }` чистятся тоже.
 * До этого проход был по верхнему уровню, и вложенный секрет уезжал
 * во внешний сервис целиком.
 */
export function redactKeys(value: unknown, allow?: RedactAllowList): unknown {
  return redactValue(value, 1, new Set<object>(), allow);
}

/**
 * Адрес события без значений секретных параметров строки запроса (`LEGACY-189`).
 *
 * 🔴 Редактор ключей сюда неприменим по форме: он маскирует ключи объекта, а
 * `req.originalUrl` — текст. Без этого разбора значение, замаскированное в
 * `query`, тем же событием уезжало открытым в `url` и вторым разом в хлебной
 * крошке, то есть маска на `query` закрывала одно место из трёх.
 *
 * ⚠️ Разбором, а не регуляркой по строке: параметр может повторяться, быть
 * пустым и содержать процентное кодирование. Путь не трогаем — без него
 * событие бесполезно.
 *
 * ⚠️ Персональные ключи обрабатываются здесь так же, как в теле (`LEGACY-332`):
 * иначе почта, ушедшая хешем из `body`, уезжала бы открытой из строки запроса.
 *
 * ⚠️ Неэкранированный `+` в значении даёт хеш, отличный от хеша того же значения
 * из тела: `URLSearchParams` применяет разбор формы и читает `+` как пробел.
 * Это **принято**, а не упущено (решение арбитра от 30.08.2026, `LEGACY-334`):
 * для строки запроса `+` как пробел — верное поведение, `req.query` через `qs`
 * делает так же, а правильно закодированный адрес несёт `%2B` и даёт тот же хеш,
 * что тело. Ручек, принимающих почту в строке запроса, в проекте нет вовсе.
 */
export function redactUrl(rawUrl: string, allow?: RedactAllowList): string {
  const queryStart = rawUrl.indexOf('?');
  if (queryStart === -1) return rawUrl;

  const pathPart = rawUrl.slice(0, queryStart);
  const params = new URLSearchParams(rawUrl.slice(queryStart + 1));
  for (const key of Array.from(new Set(params.keys()))) {
    // `?email=` в адресе — та же почта, что и в теле, и уезжает она дважды:
    // в `url` контекста и в хлебной крошке (`LEGACY-189`). Обращение одно.
    const replaced: string[] = [];
    let changed = false;
    for (const value of params.getAll(key)) {
      const item = redactByKey(key, value, allow);
      if (item) {
        replaced.push(item.value);
        changed = true;
        continue;
      }
      // Значение, которое не опознал разбор по имени, осматривается по
      // содержимому (`LEGACY-336`, `LEGACY-337`). Без этого почта, поданная
      // поисковым `q`, уезжала бы открытой и в `url` контекста, и в крошке:
      // маска на `q` запрещена — тот же параметр несёт номер заявки и слаг.
      const scanned = redactFreeText(value);
      replaced.push(scanned);
      if (scanned !== value) changed = true;
    }
    // 🔴 Ничего не изменилось — параметр не переписывается вовсе. Иначе
    // `delete` + `append` унесли бы его в хвост строки запроса, и адрес
    // события перестал бы совпадать с настоящим при нулевой правке.
    if (!changed) continue;

    // 🔴 Каждое вхождение обрабатывается своим значением, а не первым на все.
    // `params.set` заменяет все вхождения разом: на `?email=a&email=b` вторая
    // почта пропадала бы бесследно — то есть терялся ровно тот счёт разных
    // пострадавших, ради которого выбран хеш. Для секретов это было незаметно:
    // все вхождения превращаются в одинаковый `[Filtered]`.
    // Найдено ревью 30.08.2026 до коммита.
    params.delete(key);
    for (const value of replaced) params.append(key, value);
  }
  const query = params.toString();
  return query ? `${pathPart}?${query}` : pathPart;
}

/**
 * Один узел обхода: `depth` — уровень самого `value`, вход равен 1.
 *
 * ⚠️ Предел глубины проверяется **только для контейнеров**. Скаляр на любом
 * уровне уже прошёл проверку имени в цикле родителя, поэтому обрезать его
 * незачем — это стоило бы диагностики без выигрыша. Контейнер же обрезается
 * обязательно: его ключи мы не смотрели и поручиться за них не можем.
 *
 * ⚠️ `seen` — множество **текущего пути**, а не всего обхода: объект
 * добавляется перед спуском и снимается после. Глобальное множество сочло
 * бы циклом повторную ссылку на один объект из двух соседних ключей
 * и молча съело бы содержимое второй.
 */
function redactValue(
  value: unknown,
  depth: number,
  seen: Set<object>,
  allow?: RedactAllowList,
): unknown {
  const binary = describeBinary(value);
  if (binary) return binary;

  const exotic = describeExotic(value);
  if (exotic) return exotic;

  const container = getContainer(value);
  // 🔴 Единственная точка, через которую проходит **каждый** лист обхода:
  // элемент массива, значение под ключом, не совпавшим ни с одной маской,
  // и скаляр, поданный в `redactKeys` напрямую. До 01.09.2026 строка отсюда
  // возвращалась нетронутой, и разбора по значению не было нигде (`LEGACY-336`).
  if (!container) return typeof value === 'string' ? redactFreeText(value) : value;
  if (depth > MAX_REDACT_DEPTH) return '[MaxDepth]';

  if (seen.has(container)) return '[Circular]';
  seen.add(container);
  try {
    return Array.isArray(container)
      ? redactArray(container, depth, seen, allow)
      : redactObject(container, depth, seen, allow);
  } finally {
    seen.delete(container);
  }
}

/**
 * ⚠️ Ключ, совпавший с маской, заменяется целиком и **внутрь не заходим**:
 * так `authorization` с объектным значением остаётся `[Filtered]`, как было
 * до рекурсии, и ошибка тут в безопасную сторону.
 *
 * 🔴 Клон строится через `Object.create(null)`, а не литералом `{}`. `JSON.parse`
 * заводит `__proto__` обычным собственным ключом, и `Object.keys` его отдаёт;
 * но присваивание `clone['__proto__']` объекту с обычным прототипом уходит
 * в сеттер `Object.prototype.__proto__` — собственного ключа не появляется,
 * значение пропадает, а прототипом клона становится разобранное тело запроса.
 * Тело без прототипа сеттера не имеет, и присваивание кладёт обычный ключ.
 * Снятый спред `{ ...value }` этим не страдал, поэтому переход на цикл был
 * регрессией; найдено ревью 30.08.2026 до коммита.
 */
function redactObject(
  value: Record<string, unknown>,
  depth: number,
  seen: Set<object>,
  allow?: RedactAllowList,
): Record<string, unknown> {
  const clone = Object.create(null) as Record<string, unknown>;
  for (const key of Object.keys(value)) {
    const replaced = redactByKey(key, value[key], allow);
    clone[key] = replaced ? replaced.value : redactValue(value[key], depth + 1, seen, allow);
  }
  return clone;
}

function redactArray(
  value: unknown[],
  depth: number,
  seen: Set<object>,
  allow?: RedactAllowList,
): unknown[] {
  const kept = value
    .slice(0, MAX_REDACT_ARRAY_ITEMS)
    .map((item) => redactValue(item, depth + 1, seen, allow));
  const dropped = value.length - MAX_REDACT_ARRAY_ITEMS;
  if (dropped > 0) kept.push(`[Truncated: ${dropped} more]`);
  return kept;
}

/** Значение, внутрь которого редактор заходит: массив или простой объект. */
function getContainer(value: unknown): unknown[] | Record<string, unknown> | undefined {
  // `Array.isArray` сужает `unknown` до `any[]`, а не до `unknown[]` — приведение
  // возвращает проверку типов внутрь элементов, а не отключает её.
  if (Array.isArray(value)) return value as unknown[];
  return isPlainObject(value) ? value : undefined;
}

/**
 * 🔴 Двоичное тело внутрь редактора не пускается вовсе.
 *
 * На `POST /uploads/direct` тело разбирается сырым `express.raw` с любым типом
 * содержимого, то есть `req.body` там — `Buffer` размером
 * до `UPLOADS_MAX_AUDIO_MB + 10` (по умолчанию 210 МБ).
 * `Array.isArray(Buffer)` ложно, а `isPlainObject` истинно, поэтому редактор
 * разворачивал бы его в объект «ключ на байт» — сотни миллионов ключей, собираемых
 * внутри обработчика исключения, и потолок `MAX_REDACT_ARRAY_ITEMS` сюда не достаёт.
 * Проверка стоит **до** `getContainer` и отдаёт только размер: содержимое файла
 * в событии не нужно, а знать, что тело было двоичным и каким, — нужно.
 * Найдено ревью 30.08.2026 до коммита.
 */
function describeBinary(value: unknown): string | undefined {
  if (ArrayBuffer.isView(value)) return `[Binary: ${value.byteLength} bytes]`;
  if (value instanceof ArrayBuffer) return `[Binary: ${value.byteLength} bytes]`;
  return undefined;
}

/**
 * 🔴 Носитель состояния вне перечислимых собственных ключей внутрь редактора
 * не пускается — он отдаётся меткой с типом (`LEGACY-335`).
 *
 * `Date`, `Map`, `Set`, `RegExp` и `Error` проходят `isPlainObject`: они объекты,
 * не `null` и не массивы. Данные при этом лежат во внутренних слотах, `Object.keys`
 * отдаёт пустой список, и `redactObject` клонировал их в `{}` — в событии
 * не оставалось ни следа того, что там что-то было.
 *
 * ⚠️ Проверка по **прототипу**, а не по списку классов, и это главное в записи.
 * Список классов всегда неполон, и следующий класс так же тихо стал бы `{}`.
 * Здесь неизвестный не-простой объект получает метку с именем конструктора,
 * то есть неполнота перестаёт быть тихой.
 *
 * ⚠️ `Object.prototype` и `null` — единственные законные прототипы того, что
 * приходит в контекст события, и **нужны оба**. `req.body` из `express.json`
 * и `req.headers` из Node несут `Object.prototype`; `req.query` в `express@5`
 * разбирается `querystring.parse` и приходит **без прототипа вовсе**. Снять
 * ветку `proto === null` как перестраховку нельзя: строка запроса целиком
 * превратится в `[Object: unknown]`, и `redactUrl` останется единственным
 * местом, где она видна. Проверено запуском, а не по памяти.
 *
 * ⚠️ Массив сюда не доходит: его отсеивает `isPlainObject`, тот же предикат,
 * которым `getContainer` решает, заходить ли внутрь. Без этого отсева редактор
 * перестал бы заходить в массивы вовсе — прототип у них `Array.prototype`.
 *
 * ⚠️ Стоит **после** `describeBinary`: `Buffer` тоже не простой объект,
 * но про него нужен размер, а не имя класса.
 */
function describeExotic(value: unknown): string | undefined {
  // Тот же предикат, что у `getContainer`, и намеренно он же, а не своя копия:
  // признак «сюда редактор заходит» обязан быть задан в одном месте. Разъехавшись,
  // эти две ветки дали бы значению одновременно метку и попытку обхода, и обе
  // вернули бы правдоподобный результат. Найдено ревью 30.08.2026.
  if (!isPlainObject(value)) return undefined;
  const proto: unknown = Object.getPrototypeOf(value);
  if (proto === null || proto === Object.prototype) return undefined;
  return `[${describeExoticShape(value)}]`;
}

/**
 * ⚠️ Метка несёт тип и размер, но не содержимое. У `Error` берётся только `name`:
 * `message` и `stack` пишутся кодом свободно и регулярно содержат и почту,
 * и токен — то есть ровно то, что редактор и убирает.
 *
 * ⚠️ Негодная дата отдаётся меткой, а не роняет обход: `toISOString` на ней
 * бросает `RangeError`, а редактор зовётся внутри обработчика исключения,
 * где падать нельзя.
 */
function describeExoticShape(value: object): string {
  if (value instanceof Date) {
    return Number.isNaN(value.getTime()) ? 'Date: Invalid Date' : `Date: ${value.toISOString()}`;
  }
  if (value instanceof Map) return `Map: ${value.size} entries`;
  if (value instanceof Set) return `Set: ${value.size} entries`;
  if (value instanceof RegExp) return `RegExp: ${value.source}`;
  if (value instanceof Error) return `Error: ${value.name}`;
  return `Object: ${describeConstructor(value)}`;
}

/**
 * ⚠️ Имя берётся из прототипа, а не из `value.constructor`: собственный ключ
 * `constructor` в разобранном теле запроса завёл бы в метку строку из запроса.
 */
function describeConstructor(value: object): string {
  const proto: unknown = Object.getPrototypeOf(value);
  if (typeof proto !== 'object' || proto === null) return 'unknown';
  const ctor: unknown = (proto as { constructor?: unknown }).constructor;
  const name: unknown = typeof ctor === 'function' ? (ctor as { name?: unknown }).name : undefined;
  return typeof name === 'string' && name !== '' ? name : 'unknown';
}

function isPlainObject(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}
