/**
 * `%`, `_` и `\` в строке пользователя — символы, а не подстановки `LIKE`/`ILIKE`: поиск «100%»
 * иначе совпал бы со всем разом. Обратная косая — escape-символ `LIKE` в Postgres по умолчанию,
 * поэтому экранируется и она сама; в сыром SQL — пара с `ESCAPE '\\'`, в фильтре Prisma
 * `contains` — как есть.
 *
 * Одно место на все поиски (`LEGACY-462`): правило одно, и поправленное в одной копии из трёх
 * оно разошлось бы молча.
 */
export function escapeLikeWildcards(term: string): string {
  return term.replace(/([\\%_])/g, '\\$1');
}
