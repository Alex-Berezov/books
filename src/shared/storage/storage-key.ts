/**
 * Ключ хранилища в том виде, в каком он стоит в публичном адресе R2: каждый сегмент закодирован
 * `encodeURIComponent`, разделители `/` сохранены. Одна функция на выдачу адреса R2
 * (`R2StorageService.getPublicUrl`) и на поиск ссылок на медиа (`LEGACY-421`): разойдись они,
 * критерий сироты перестал бы узнавать адреса, которые сам же и выдаёт. Локальное хранилище
 * адрес не кодирует — его адрес содержит ключ как есть, и сырая форма ключа ищется всегда.
 */
export function encodeKeyPath(key: string): string {
  return key.split('/').map(encodeURIComponent).join('/');
}
