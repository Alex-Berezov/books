#!/usr/bin/env bash
#
# Сообщение в тот же Telegram-канал, что и у Alertmanager, из job'ов `deploy.yml`.
#
# Вызов: notify_telegram.sh <заголовок> [строка...]
#   Заголовок уходит жирным, остальные строки — как есть, по одной на строку.
#   Каждый аргумент экранируется под `parse_mode=HTML`: версия приходит из входа
#   `workflow_dispatch` и может содержать `&`, `<`, `>` (ветка `feature/a<b>`), а
#   Telegram на таком отвечает 400 — то есть сообщение не доходит именно тогда,
#   когда оно нужно.
#
# Секреты передаются переменными окружения `TG_TOKEN` и `TG_CHAT`, а не аргументами:
# GitHub маскирует в логах только точные совпадения со значением секрета, и токен,
# попавший в командную строку, виден в трассировке. Ни `echo` токена, ни `set -x`
# в этом файле быть не должно.
#
# 🔴 Скрипт всегда выходит нулём. Отказ доставки — это предупреждение, а не красный
# выкат: канал молчит, но прод от этого не сломан. Обратное поведение однажды
# уронило бы выкат из-за недоступности api.telegram.org.
#
# 🔴 Код ответа проверяется обязательно. Telegram отвечает на отозванный токен `401`,
# на выкинутого из канала бота `403`, на битый chat_id `400` — и всё это с телом JSON
# и кодом возврата curl 0. Без проверки шаг зелёный, в логе пусто, до человека не
# дошло ничего: это исходное состояние LEGACY-221, только с галкой.
#
# ⚠️ Это **единственный** отправитель в канал со стороны GitHub. Прямых обращений к
# `api.telegram.org` в `.github/workflows/**` быть не должно ни одного, и это проверяет
# `src/devops/deploy-trigger.spec.ts`. Первая редакция `LEGACY-241` держала вторую копию
# тела прямо в шаге `🚨 Notify Failure` — у job `notify` тогда не было `actions/checkout`.
# Отправителей стало четыре (окно открыть, окно закрыть, отказ, отмена), сторож сверял
# копии по подстрокам, и замена `sed` на равный по смыслу `printf` красила проверку, а
# расхождение по `--max-time` или `chat_id` не красило ничего. Копию убрали, чекаут в
# `notify` завели.
#
# ⚠️ Цена размена названа прямо: сообщение об упавшем выкате теперь зависит от того, что
# `📥 Checkout Notifier` отработал. Поэтому тот чекаут пришпилен к ветке по умолчанию, а
# не к выкатываемому ref'у: повторный запуск прогона по старому тегу иначе остался бы без
# файла. Отказ самого чекаута красит job `notify` и виден в списке прогонов.

set -euo pipefail

if [[ $# -lt 1 || -z "${1}" ]]; then
  echo "::warning::notify_telegram.sh вызван без текста — сообщение не отправлено"
  exit 0
fi

esc() { printf '%s' "${1}" | sed -e 's/&/\&amp;/g' -e 's/</\&lt;/g' -e 's/>/\&gt;/g'; }

TEXT="<b>$(esc "${1}")</b>"
shift
for line in "$@"; do
  [[ -z "${line}" ]] && continue
  TEXT="${TEXT}"$'\n'"$(esc "${line}")"
done

if [[ -z "${TG_TOKEN:-}" || -z "${TG_CHAT:-}" ]]; then
  echo "::warning::TELEGRAM_BOT_TOKEN или TELEGRAM_CHAT_ID не заданы — сообщение не отправлено"
  exit 0
fi

# --data-urlencode, а не -d: в тексте переносы строк и символы, которые -d
# отправил бы как есть и сломал бы форму запроса.
#
# `set +e` на время вызова: при `set -e` сетевой отказ оборвал бы скрипт до печати
# предупреждения. Дописывать `|| echo "000"` нельзя — curl при отказе соединения сам
# печатает `000` и возвращает ненулевой код, и в переменную попало бы `000000`.
set +e
HTTP_CODE=$(curl -sS --max-time 20 -o /dev/null -w '%{http_code}' \
  "https://api.telegram.org/bot${TG_TOKEN}/sendMessage" \
  --data-urlencode "chat_id=${TG_CHAT}" \
  --data-urlencode "parse_mode=HTML" \
  --data-urlencode "text=${TEXT}")
set -e

if [[ "${HTTP_CODE}" != "200" ]]; then
  echo "::warning::Telegram отклонил сообщение: HTTP ${HTTP_CODE}. Проверь TELEGRAM_BOT_TOKEN, TELEGRAM_CHAT_ID и что бот остался администратором канала."
else
  echo "Telegram: сообщение доставлено"
fi
