-- LEGACY-005, сжатие (ADR-018). Последний шаг трёхшагового снятия колонки.
--
-- Предыдущий образ — v1.0.98, он работает на проде с 19.09.2026 и служит целью отката.
-- Колонку он НЕ НАЗЫВАЕТ: поле помечено @ignore в его prisma/schema.prisma, поэтому
-- генератор не включает её ни в SELECT, ни в список колонок INSERT. Проверено прогоном,
-- а не рассуждением: клиент из схемы того тега против базы без колонки даёт P2003
-- на фиктивном внешнем ключе, а не P2022 — ни у findMany без select, ни у create,
-- createMany и upsert.
--
-- Данные не теряются: замер на проде 18.09.2026 — 460 строк BookCategory, ноль с isPrimary
-- = true; в true колонку не писал ни один путь, главную категорию версии держит
-- BookVersion.primaryCategoryId.
--
-- Частичный уникальный индекс этой колонки снят предыдущим релизом
-- (20260919120000_legacy_005_drop_isprimary_index), поэтому здесь его уже нет.
--
-- IF EXISTS намеренно: migrate deploy не оборачивает файл в транзакцию, и повтор поверх
-- частично применённого состояния (после ручного migrate resolve --rolled-back) обязан
-- быть безопасным.
ALTER TABLE "BookCategory" DROP COLUMN IF EXISTS "isPrimary";
