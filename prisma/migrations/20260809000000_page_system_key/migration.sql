-- Неизменяемый ключ системных страниц (A2, `tasks/system-pages-slug/TASK.md`).
--
-- Пять страниц — главная и четыре хаба таксономий — сайт ищет сам, по значению,
-- зашитому в код. До сих пор этим значением был слаг: редактируемое поле, которое
-- админка генерирует из заголовка. Переименование заголовка переписывало слаг, и
-- связь рвалась беззвучно — ошибки не возникало, главная переходила на словарные
-- строки, а хабы теряли metaTitle, metaDescription, h1, SEO-текст и FAQ. Один такой
-- случай на проде уже был: `homepage-index` стал `homepage`.
--
-- Колонка nullable и добавляется без значения по умолчанию, поэтому ALTER не
-- переписывает таблицу и не блокирует чтение. Старый код новую колонку не видит:
-- миграция безопасна и до, и после выката образа.

ALTER TABLE "Page" ADD COLUMN "system_key" TEXT;

-- Бэкфилл по нынешним слагам — единственный доступный источник соответствия.
-- Состояние прода проверено прямо перед написанием миграции: все 25 сочетаний
-- (5 страниц × 5 языков) существуют **каждое в своём языке** и опубликованы,
-- проверено по полю `language` в ответе, а не по коду 200 — публичный резолвер
-- умеет отдать чужой язык вместо запрошенного, и 200 сам по себе ничего не значит.
--
-- ⚠️ Если к моменту применения слаг всё-таки успел уехать, строка останется с NULL,
-- и её хаб потеряет SEO-контент. Молчанием это не будет: `SystemPagesService`
-- проверяет ровно эти ключи на старте приложения и пишет logger.error по каждой
-- недостающей странице с перечислением языков.
UPDATE "Page" SET "system_key" = 'homepage'              WHERE "slug" = 'homepage-index';
UPDATE "Page" SET "system_key" = 'taxonomy-categories'   WHERE "slug" = 'taxonomy-categories-index';
UPDATE "Page" SET "system_key" = 'taxonomy-genres'       WHERE "slug" = 'taxonomy-genres-index';
UPDATE "Page" SET "system_key" = 'taxonomy-collections'  WHERE "slug" = 'taxonomy-collections-index';
UPDATE "Page" SET "system_key" = 'taxonomy-tags'         WHERE "slug" = 'taxonomy-tags-index';

-- Уникальность составная: страница существует один раз в каждом языке, пять строк
-- на ключ. Глобальный UNIQUE, как записан в тексте задачи, отверг бы второй же язык.
-- Обычные страницы под ограничение не попадают: NULL в Postgres не равен NULL.
CREATE UNIQUE INDEX "Page_language_system_key_key" ON "Page" ("language", "system_key");
