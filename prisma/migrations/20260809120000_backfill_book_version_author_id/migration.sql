-- Бэкфилл `BookVersion.authorId` (шаг 2 `tasks/authors-indexability/TASK.md`).
--
-- Внешний ключ на автора существовал в схеме, принимался в DTO и читался кодом —
-- но его не проставлял никто. Замер на проде 09.08.2026: **45 версий из 45 с
-- NULL**, включая все 40 опубликованных. Фактическая связь книги с автором
-- держалась на строковом поле `BookVersion.author`.
--
-- Стоило это следующего: список авторов считал `_count.bookVersions` по этому
-- ключу и показывал «0 книг» **всем десяти** авторам, включая тех, чьи книги
-- лежат в каталоге. Страница автора при этом книги показывала — у неё был
-- fallback по имени. То есть расходились не данные, а сигналы: список говорил
-- одно, страница другое.
--
-- ⚠️ Строковый матчинг хрупок в общем случае («Sun Tzu» / «Sunzi», инициалы,
-- лишние пробелы), поэтому качество совпадений проверено **до** этого UPDATE,
-- отдельным SELECT'ом на живой базе:
--
--   match_quality | versions
--   --------------+---------
--   exactly one   |      45
--
-- Ни одной версии без совпадения и ни одной с неоднозначным — сопоставление по
-- паре (язык, имя) разрешилось однозначно для всех. Разбивка по авторам совпала
-- с независимо снятым эталоном через `GET /api/en/authors/{slug}`: восемь авторов
-- по одной книге, у `homer` все версии черновики, у `fyodor-dostoevsky` версий нет.
--
-- Сопоставление идёт **внутри своего языка**: в ru-версии книги автор записан как
-- «Сунь-цзы», и сверять его с английским «Sun Tzu» бессмысленно.

UPDATE "BookVersion" bv
SET "authorId" = t."authorId"
FROM "AuthorTranslation" t
WHERE bv."authorId" IS NULL
  AND t.language = bv.language
  AND t.name = bv.author
  -- Защита от неоднозначности на будущих данных: если то же имя в том же языке
  -- принадлежит нескольким авторам, версия остаётся с NULL. Пустой ключ честнее
  -- произвольно выбранного — поштучный резолвинг по имени всё равно работает.
  AND (
    SELECT COUNT(DISTINCT t2."authorId")
    FROM "AuthorTranslation" t2
    WHERE t2.language = bv.language AND t2.name = bv.author
  ) = 1;
