-- LEGACY-005, расширение перед сжатием (ADR-018).
--
-- Снимается только частичный уникальный индекс. Колонка "isPrimary" ОСТАЁТСЯ в базе:
-- клиент Prisma строит список колонок INSERT из схемы, по которой собран, а не из `select`
-- вызова, поэтому образ v1.0.97 называет её в каждом INSERT (проверено: create, createMany
-- и upsert дают P2022 против базы без колонки). Этим тегом поле уходит из клиента через
-- @ignore, а DROP COLUMN уезжает следующим — тогда его предыдущий образ колонку уже не знает.
-- Тег на тот релиз ставит владелец: разрушительную миграцию агент пишет, но не выкатывает.
--
-- DROP INDEX идемпотентен: migrate deploy не оборачивает файл в транзакцию, и повтор
-- поверх частично применённого состояния (после ручного migrate resolve --rolled-back)
-- обязан быть безопасным.
--
-- Для v1.0.97 снятие индекса безопасно: имя BookCategory_bookVersionId_isPrimary_key
-- в src, libs и test не встречается, конфликт-таргет upsert — bookVersionId_categoryId
-- (другой индекс), а в true колонка не пишется ни одним путём, поэтому уникальность,
-- которую индекс стерёг, ни на что не опиралась.
DROP INDEX IF EXISTS "BookCategory_bookVersionId_isPrimary_key";
