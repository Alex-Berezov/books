-- `LEGACY-015`, пачка `V1`: охват журнала административных действий расширен на два
-- случая - публикацию версии книги (`VERSION_PUBLISHED`, парное к уже живому
-- `VERSION_UNPUBLISHED`) и удаление пользователя (`USER_DELETED`, рядом с `ROLE_REVOKED`
-- на каждую снятую роль). Типу объекта новые значения не нужны: оба события ложатся
-- на существующие `BOOK_VERSION` и `USER` (решение арбитра 20.09.2026).
--
-- Миграция только добавляющая: ни `DROP`, ни `RENAME`, ни сужения типа, ни правки
-- существующих значений. Значение перечисления в Postgres удалить нельзя вовсе, поэтому
-- откат образа ничего не теряет - прежний образ этих значений не пишет и не читает
-- (ADR-018): строк с ними в базе до выката нового образа не появляется, а ручки чтения
-- журнала нет вовсе.
--
-- Идемпотентна намеренно, как и оба предшественника
-- (`20260911150000_legacy_015_admin_audit_event`, `20260912120000_legacy_180_audit_version_unpublished`):
-- оборванный накат оставил бы строку с `finished_at = NULL` в `_prisma_migrations`,
-- а она отвергает `P3009` **любую** следующую пачку миграций до ручного `migrate resolve`
-- на боевой машине, то есть до владельца. `scripts/docker-entrypoint.sh` отказ
-- `migrate deploy` глотает, поэтому наружу такой выкат выглядит зелёным.
--
-- `ADD VALUE` в Postgres 12+ не переписывает таблиц: значение дописывается в каталог
-- типа, данные не трогаются, блокировка на таблицы не берётся. Добавленное значение
-- нельзя использовать в `INSERT`/`WHERE` этой же миграции - здесь оно и не используется.

-- AlterEnum
ALTER TYPE "AdminAuditAction" ADD VALUE IF NOT EXISTS 'VERSION_PUBLISHED';

-- AlterEnum
ALTER TYPE "AdminAuditAction" ADD VALUE IF NOT EXISTS 'USER_DELETED';
