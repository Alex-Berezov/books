-- LEGACY-276, релиз 2 из двух: возврат уникальности базового слага категории.
--
-- Индекс с этим именем уже существовал и был снят намеренно миграцией
-- 20250830151000_add_taxonomy_translations (комментарий там: "slugs are now unique per
-- translation language"). Решение владельца 18.09.2026 (вариант D, work-queue.md) вернуло
-- прежнее ограничение: базовый слаг не является публичным адресом (им стал
-- CategoryTranslation.slug), но остаётся входом для legacy-URL, фолбэком в крошках
-- и признаком «адрес ещё жив» в бухгалтерии редиректов, и для всех трёх ролей два термина
-- на одном базовом слаге дают недетерминированный результат.
--
-- CREATE UNIQUE INDEX на живых данных — класс 2 по ADR-018: то, что пишет предыдущий образ,
-- начинает нарушать ограничение, которого секунду назад не было. Релиз 1 этой записи
-- (v1.0.100, 19.09.2026) закрыл все четыре писателя базового слага advisory-замком
-- и общей проверкой assertSlugFree в CategoryTreeService и завёл обработку P2002
-- на update (её не было). Этот релиз — сжатие: сам рубеж в базе. Причина третьего вида
-- записи в migration-compat-allowlist.json называет образ v1.0.100 и доказывает, что его
-- клиент этой миграцией не ломается.
--
-- Данные. Миграция не удаляет и не изменяет ни одной строки. На дублях она падает целиком
-- (23505) — Prisma отдаёт файл одним скриптом, то есть одним неявным транзакционным блоком.
--
-- ⚠️ Чем стоит отказ. Упавшая миграция оставляет в _prisma_migrations строку
-- с finished_at = NULL, и после неё ЛЮБОЙ следующий `prisma migrate deploy` отвергает всю
-- пачку с P3009 до ручного `prisma migrate resolve` на боевой машине — то есть до владельца
-- (books-app-docs/backend/guides/migration-failure-runbook.md). Наружу это выглядит зелёным
-- выкатом: scripts/docker-entrypoint.sh глотает отказ миграций через `|| echo`, и контейнер
-- поднимается как обычно (ADR-018, раздел «Цена», — там же сказано, почему эту строку
-- нельзя менять без замены механизма). Поэтому свежий счёт дублей Category.slug перед
-- выкатом обязателен: замер 18.09.2026 дал ноль, но он сделан до выката релиза 1, а окно
-- наступает после.
--
-- Идемпотентность — двумя операторами, и разделение тут вынужденное.
--
-- `CREATE UNIQUE INDEX IF NOT EXISTS` сам по себе не лекарство, а вторая закладка: под уже
-- занятым именем он молча ничего не делает, каким бы индекс ни был, — ровно так индексы
-- Like_* год простояли частичными (LEGACY-367). Поэтому перед ним стоит DO-блок, который
-- НИЧЕГО не создаёт, а только проверяет: если имя занято и под ним не «UNIQUE по одной
-- колонке slug, не частичный» — отказ с внятным текстом, потому что «применено»
-- при отсутствующей уникальности хуже красной миграции. Если индекс правильный (штатный
-- случай: дежурный собрал его руками после отказа на дублях) — блок молчит, а следующий
-- оператор становится пустой операцией.
--
-- 🔴 Почему создание вынесено из блока: scripts/drift-check.mjs читает миграции статически
-- и `CREATE UNIQUE INDEX` внутри `DO $$ … $$` не видит — он честно сообщает
-- «UNREADABLE … / MISSING in migrations» и краснеет. Ослаблять гейт нельзя, а прятать
-- от него создание индекса — тем более: именно этот гейт и ловит расхождение схемы
-- с миграциями. Отсюда порядок: проверка в блоке, создание — плоским оператором, который
-- гейт разбирает.
--
-- Locks. CREATE UNIQUE INDEX берёт на "Category" SHARE и держит его до конца файла:
-- чтения идут, записи ждут. Сама сборка сначала встаёт за любой уже открытой транзакцией
-- писателя таксономии (CATEGORY_TREE_TX_OPTIONS = { timeout: 30_000 },
-- src/modules/category/category-tree.service.ts), а в это окно POST/PATCH /categories
-- и партия импорта стоят за SHARE и при упоре в свой потолок отвечают 500 по P2028.
-- Таблица маленькая (замер на проде 18.09.2026 — десятки строк), поэтому окно измеряется
-- миллисекундами. CONCURRENTLY невозможен: он не работает внутри транзакционного блока,
-- которым Prisma и отдаёт этот файл. lock_timeout не ставим намеренно — миграция, снятая
-- по таймауту, остаётся на боевой машине failed (P3009) и требует ручного `migrate resolve`
-- там же, то есть меняет дешёвое ожидание на тему владельца (тот же довод, что
-- в 20260916120000_legacy_367_index_drift).

DO $$
BEGIN
  IF EXISTS (
    SELECT 1 FROM pg_class c
      JOIN pg_namespace n ON n.oid = c.relnamespace
     WHERE c.relname = 'Category_slug_key'
       AND c.relkind = 'i'
       AND n.nspname = current_schema()
  ) AND NOT EXISTS (
    SELECT 1
      FROM pg_index i
      JOIN pg_class c ON c.oid = i.indexrelid
      JOIN pg_class t ON t.oid = i.indrelid
     WHERE c.relname = 'Category_slug_key'
       AND t.relname = 'Category'
       AND i.indisunique
       AND i.indpred IS NULL
       AND i.indnkeyatts = 1
       AND (
         SELECT a.attname FROM pg_attribute a
          WHERE a.attrelid = t.oid AND a.attnum = i.indkey[0]
       ) = 'slug'
  ) THEN
    RAISE EXCEPTION
      'LEGACY-276: "Category_slug_key" уже существует, но это не полный UNIQUE по Category(slug). Применённой такую миграцию считать нельзя: уникальности, которую обещает schema.prisma, в базе нет (класс LEGACY-367).';
  END IF;
END $$;

CREATE UNIQUE INDEX IF NOT EXISTS "Category_slug_key" ON "Category"("slug");
